"""FB summaries: which targets help fantasy forecasts, negative findings, fantasy claims ledger, player-level manifest.

Outputs (all generated from the result CSVs; no hand-typed numbers)
  fantasy/summary.md                 "Which of the six targets help fantasy forecasting, which do not, and when?"
  fantasy/negative_findings.md       every null and harmful result, as prominently as the gains
  fantasy/claims_to_evidence.csv     fantasy claims with evidence tier (master prompt §I3) and source rows
  fantasy/player_level_manifest.json schema, row counts and SHA-256 of the git-ignored player-level files
"""
from __future__ import annotations

import json

import pandas as pd

import fb_lib as F

TL = {"woba": "wOBA", "br": "baserunning run-value rate", "fld": "fielding run-value rate", "hwar": "hitter bWAR/600 PA",
      "fip": "FIP", "pwar": "pitcher bWAR/200 IP", "woba+br+hwar": "all hitter target forecasts", "fip+pwar": "both pitcher target forecasts",
      "sprint_speed": "sprint speed (raw)", "xwoba_w2": "two-year xwOBA (raw)", "barrel_pct": "Barrel% (raw)", "stuff_plus": "Stuff+ (raw)",
      "k_pct": "K% (raw)", "k_bb_pct": "K-BB% (raw)"}
OL = {"VAL_H": "hitter 5×5 value", "VAL_P": "pitcher 5×5 value", "PTS_H": "Yahoo hitter points", "PTS_P": "Yahoo pitcher points"}
KIND = {"target_forecast_added": "target forecast added to the category baseline", "admitted_vs_history_target_forecast": "admitted vs history-only target forecast",
        "joint_target_forecasts": "all target forecasts jointly", "joint_admitted_vs_history": "joint admitted vs joint history-only", "direct_metric_added": "raw metric added"}


def fmt(r):
    return f"{r.delta_pct:+.2f}% [{r.ci_low_pct:+.2f}, {r.ci_high_pct:+.2f}]".replace("-", "−")


def main():
    r = pd.read_csv(F.FANTASY / "results_by_target_category.csv")
    P = r[r["sample"].str.startswith("2021")]
    E = r[r["sample"].str.startswith("2026")]
    prim = P[P.family == "primary"]
    tf = P[P.kind == "target_forecast_added"]

    # ---------------- summary
    lines = ["# Which of the six targets help fantasy forecasting, which do not, and when?", "",
             "Generated by `experiments/fb05_summaries.py` from `results_by_target_category.csv`. Evidence tier: **exploratory fantasy linkage**. The protocol "
             "(`experiment_protocol.md`) was committed and pushed before any fantasy model was fit. Outcome seasons 2021–2025 are pooled for the primary results; "
             "2026 is exploratory. ΔRMSE is the change in out-of-time error of the fantasy-category forecast when the target forecast is added to a direct "
             "category-history model; negative is better. Intervals are 95% paired player-cluster bootstrap intervals.", "",
             "## The eight pre-specified primary linkages (Holm-adjusted)", "",
             "| Linkage | ΔRMSE % [95% CI] | Holm p | Seasons improved | Verdict |", "|---|---|---|---|---|"]
    for _, x in prim.iterrows():
        lines.append(f"| {TL[x.target]} → {OL.get(x.outcome, x.outcome)} | {fmt(x)} | {x.p_adjusted:.3f} | {int(x.years_improved)}/5 | {x.verdict} |")
    lines += ["", "## Target by target", ""]
    for t in ["woba", "fip", "br", "fld", "hwar", "pwar"]:
        g = tf[tf.target == t]
        adds = g[g.verdict == "adds information"]
        weak = g[g.verdict == "gain not robust to multiplicity"]
        lines.append(f"**{TL[t]} forecast.** Adds information for: " + (", ".join(f"{OL.get(o, o)} ({fmt(x)})" for o, x in zip(adds.outcome, adds.itertuples())) or "none")
                     + ". Gain not robust to multiplicity for: " + (", ".join(OL.get(o, o) for o in weak.outcome) or "none") + ". No detectable gain for: "
                     + (", ".join(OL.get(o, o) for o in g[g.verdict == "no detectable gain"].outcome) or "none") + ".")
        lines.append("")
    d = P[P.kind == "direct_metric_added"]
    lines += ["## Raw public metrics added directly to the category model", ""]
    for _, x in d.iterrows():
        lines.append(f"- {TL[x.target]} → {OL.get(x.outcome, x.outcome)}: {fmt(x)}; BH q = {x.p_adjusted:.3f}; {x.verdict}.")
    lines += ["", "## Conditions", "",
              "- **Population.** Established major leaguers only: ≥150 PA, or the FIP study's innings floor, in the prior season. Non-returners are kept and score zero in counting categories. Rookies are excluded.",
              "- **Ratio categories.** AVG, ERA and WHIP are conditional on playing (≥100 AB / ≥20 IP next season) and weighted by volume.",
              "- **Formats.** Primary: 5×5 rotisserie, Yahoo default categories. Sensitivity: Yahoo default H2H points.",
              "- **2026.** None of the eight primary linkages had an interval excluding zero in 2026: one season, low power, and the season had already been inspected for the six targets.",
              "- **Decisions.** In the illustrative draft backtest, rank agreement with realized value rose by about 0.02 Spearman, but the players picked were not detectably better (see `ranking_value_sensitivity.csv`)."]
    (F.FANTASY / "summary.md").write_text("\n".join(lines) + "\n")

    # ---------------- negative findings
    neg = P[P.verdict.isin(["no detectable gain", "harmful", "gain not robust to multiplicity"])]
    nl = ["# Negative and null findings (fantasy bridge)", "", "Reported with the same prominence as the gains. Generated from `results_by_target_category.csv`.", "",
          f"- Pooled 2021–2025 comparisons: {len(P)}; adds information: {int((P.verdict == 'adds information').sum())}; not robust to multiplicity: "
          f"{int((P.verdict == 'gain not robust to multiplicity').sum())}; no detectable gain: {int((P.verdict == 'no detectable gain').sum())}; harmful: {int((P.verdict == 'harmful').sum())}.",
          f"- Primary family: {int((prim.verdict == 'adds information').sum())} of 8 linkages add information (FIP → ERA, FIP → WHIP). The other six do not survive Holm adjustment.",
          "- Harmful: the admitted hitter-WAR forecast was worse than the history-only hitter-WAR forecast for AVG, in 2021–2025 and again in 2026.",
          "- Boundary case: the fielding forecast added nothing to hitter 5×5 value, at-bats or any category.",
          "- The baserunning run-value forecast added nothing to stolen-base forecasts. Raw sprint speed did.",
          "- Stuff+, K% and K-BB% added nothing to K, ERA or WHIP beyond the category history.",
          "- Illustrative draft: no league size at which the augmented ranking picked detectably better players.", "",
          "| Group | Outcome | Comparison | Added | ΔRMSE % [95% CI] | Adjusted p | Verdict |", "|---|---|---|---|---|---|---|"]
    for _, x in neg.sort_values(["kind", "group", "outcome"]).iterrows():
        nl.append(f"| {x.group} | {OL.get(x.outcome, x.outcome)} | {KIND[x.kind]} | {TL.get(x.target, x.target)} | {fmt(x)} | {x.p_adjusted:.3f} | {x.verdict} |")
    (F.FANTASY / "negative_findings.md").write_text("\n".join(nl) + "\n")

    # ---------------- fantasy claims ledger (tiers per master prompt §I3)
    rows = []
    for _, x in P.iterrows():
        tier = {"adds information": "F: fantasy connection supported by matched-sample out-of-time lift (exploratory)",
                "gain not robust to multiplicity": "F-: interval excludes zero but not robust to multiplicity (exploratory)",
                "no detectable gain": "null: no detectable out-of-time lift", "harmful": "harmful: augmented forecast worse"}[x.verdict]
        rows.append({"claim": f"{TL.get(x.target, x.target)} → {OL.get(x.outcome, x.outcome)} ({KIND[x.kind]})", "value": fmt(x), "adjusted_p": round(x.p_adjusted, 4),
                     "adjustment": x.adjustment, "tier": tier, "sample": x["sample"], "source": "fantasy/results_by_target_category.csv"})
    l1 = pd.read_csv(F.FANTASY / "level1_correlations.csv")
    for _, x in l1.iterrows():
        rows.append({"claim": f"Spearman correlation, {TL[x.target_forecast]} forecast with {OL.get(x.fantasy_outcome, x.fantasy_outcome)}", "value": f"{x.spearman_2021_2025:.3f} [{x.ci_low:.3f}, {x.ci_high:.3f}]",
                     "adjusted_p": None, "adjustment": "", "tier": "E: fantasy connection supported only by correlation (association, not incremental value)",
                     "sample": "2021-2025", "source": "fantasy/level1_correlations.csv"})
    rv = pd.read_csv(F.FANTASY / "ranking_value_sensitivity.csv")
    for _, x in rv[rv["sample"].str.startswith("2021")].iterrows():
        rows.append({"claim": f"Illustrative draft backtest, {x.group}, {x.format}, top {int(x.k)}: Δ mean realized value per pick", "value": f"{x.delta_mean_realized_value:+.3f} [{x.ci_low:+.3f}, {x.ci_high:+.3f}]",
                     "adjusted_p": None, "adjustment": "", "tier": "G: decision backtest, illustrative only (no ADP, positions or in-season moves)",
                     "sample": x["sample"], "source": "fantasy/ranking_value_sensitivity.csv"})
    pd.DataFrame(rows).to_csv(F.FANTASY / "claims_to_evidence.csv", index=False)

    # ---------------- player-level manifest (files stay local, git-ignored)
    man = {"note": "Player-level files are rights-restricted derived data (MLBAM / Sports Reference sources). They are git-ignored and rebuilt by fb01-fb04. "
                   "Hashes let a rebuild be verified.", "files": {}}
    for f in sorted(F.LOCAL.glob("*.parquet")):
        df = pd.read_parquet(f)
        man["files"][f.name] = {"rows": int(len(df)), "columns": list(map(str, df.columns))[:60], "sha256": F.sha256(f)}
    (F.FANTASY / "player_level_manifest.json").write_text(json.dumps(man, indent=2))
    print("summary, negative findings,", len(rows), "claims; manifest of", len(man["files"]), "files")


if __name__ == "__main__":
    main()
