"""Generate fantasy_refs.py (citation strings) from the verified source table fantasy/research_sources.md."""
from __future__ import annotations

import re
from datetime import date
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "fantasy" / "research_sources.md"
OVERRIDE_DATE = {"S06": "n.d.; rules page for the 2027 season", "S03": "updated 2026-11-09"}
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]


def fmt_date(s: str) -> str:
    if s.startswith("n.d."):
        return f"({s})"
    m = re.search(r"(\d{4})-(\d{2})-(\d{2})", s)
    if m and not s.lower().startswith(("updated", "page updated")):
        y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3))
        return f"({y}, {MONTHS[mo - 1]} {d})"
    if m:
        return f"(n.d.; updated {m.group(0)})"
    m = re.match(r"^(\d{4})\b", s.strip())
    return f"({m.group(1)})" if m else "(n.d.)"


def main():
    refs = {}
    for line in SRC.read_text().splitlines():
        if not re.match(r"^\| S\d{2} \|", line):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        sid, title, author, url, pub = cells[0], cells[1], cells[2], cells[3], cells[4]
        first_url = url.split(";")[0].strip()
        title = re.sub(r"\s*\((title per URL|URL slug:[^)]*|URL:[^)]*)\)", "", title.split(";")[0]).strip()
        author = re.sub(r"\s*\(\d{4}\)$", "", author.split(";")[0].strip())
        pub = OVERRIDE_DATE.get(sid, pub.split(";")[0])
        m1 = re.match(r"^([A-Z][\w'.-]+(?: [A-Z][\w'.-]+){1,2}) / ([^;]+)$", author)
        if m1 and "," not in m1.group(1):
            parts = m1.group(1).split()
            who = f"{parts[-1]}, " + " ".join(p[0] + "." for p in parts[:-1])
            refs[f"fa:{sid}"] = f"{who} {fmt_date(pub)}. *{title}*. {m1.group(2).strip()}. Retrieved November 13, 2026, from {first_url}"
        else:
            refs[f"fa:{sid}"] = f"{author}. {fmt_date(pub)}. *{title}*. Retrieved November 13, 2026, from {first_url}"
    out = Path(__file__).resolve().parent / "fantasy_refs.py"
    body = "\n".join(f"    {k!r}: {v!r}," for k, v in refs.items())
    out.write_text(f'"""Generated by make_fantasy_refs.py from fantasy/research_sources.md on {date.today()}. Do not edit by hand."""\nFANTASY_REFS = {{\n{body}\n}}\n')
    print(len(refs), "fantasy references")


if __name__ == "__main__":
    main()
